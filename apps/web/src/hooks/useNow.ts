import { useEffect, useState } from 'react';

/**
 * KS-2795. Хук-тикер: возвращает «текущее время» (Date.now()) и
 * пересчитывает его каждые `intervalMs` миллисекунд (по умолчанию 30 сек).
 *
 * Используется для рендера relative-time («3 минуты назад») под мини-доской
 * партии трансляции — без него подпись «застывает» на моменте mount'а.
 * Интервал 30 сек выбран как разумный компромисс: точность отображения
 * (минутная шкала) против лишних ре-рендеров; для секундной шкалы (первые
 * 60 сек после хода) визуально не критично, что подпись обновится с
 * задержкой до 30с.
 *
 * Один общий тикер на компонент достаточен — если в дереве несколько
 * карточек, каждая вызывает свой `useNow`, что даёт независимые тики;
 * перерисовка дешёвая (re-render только подпись).
 */
export function useNow(intervalMs: number = 30_000): number {
  const [now, setNow] = useState<number>(() => Date.now());
  useEffect(() => {
    const id = setInterval(() => setNow(Date.now()), intervalMs);
    return () => clearInterval(id);
  }, [intervalMs]);
  return now;
}
